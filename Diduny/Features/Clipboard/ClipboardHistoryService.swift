import AppKit

/// What the clipboard watcher needs from a pasteboard; tests pass a fake, never the real one.
@MainActor
protocol ClipboardPasteboard: AnyObject {
    var changeCount: Int { get }
    /// Every type of every item.
    var types: [String] { get }
    func string() -> String?
    /// PNG or TIFF data of a copied image.
    func imageData() -> Data?
    /// The file URLs of a copy made in Finder or another app.
    func fileURLs() -> [URL]
    func write(text: String)
    func write(png: Data)
    func write(fileURLs: [URL])
}

@MainActor
final class GeneralClipboardPasteboard: ClipboardPasteboard {
    private let pasteboard = NSPasteboard.general

    var changeCount: Int { pasteboard.changeCount }

    var types: [String] {
        let itemTypes = (pasteboard.pasteboardItems ?? []).flatMap(\.types)
        return ((pasteboard.types ?? []) + itemTypes).map(\.rawValue)
    }

    func string() -> String? { pasteboard.string(forType: .string) }

    func imageData() -> Data? { pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) }

    func fileURLs() -> [URL] {
        pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
    }

    func write(text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    func write(png: Data) {
        pasteboard.clearContents()
        pasteboard.setData(png, forType: .png)
    }

    func write(fileURLs: [URL]) {
        pasteboard.clearContents()
        pasteboard.writeObjects(fileURLs as [NSURL])
    }
}

/// Watches the general pasteboard and keeps what was copied (plain text, images and file paths) in
/// `ClipboardHistoryStore`. Nothing leaves this Mac and entry text is never logged.
@MainActor
final class ClipboardHistoryService {
    static let shared = ClipboardHistoryService()

    static let pollInterval: TimeInterval = 0.35
    static let pruneInterval: TimeInterval = 60

    /// A copy that carries one of these types is never kept (nspasteboard.org and 1Password's own type).
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// "Skip password managers": nothing is kept while one of these apps is frontmost.
    static let passwordManagerBundleIDs: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
        "org.keepassxc.keepassxc",
        "in.sinew.Enpass-Desktop",
        "me.proton.pass.electron",
        "com.markmcguill.strongbox.mac",
        "com.nordpass.macos.NordPass",
        "com.callpod.keepermac.lite",
        "com.outercorner.Secrets",
    ]

    /// A copy that carries this type is a file copy: its paths are kept, whatever else it carries.
    private static let fileURLType = NSPasteboard.PasteboardType.fileURL.rawValue

    let store: ClipboardHistoryStore
    private let pasteboard: ClipboardPasteboard
    private let settings: SettingsStorage
    private let frontmostApp: () -> ClipboardSourceApp
    private let now: () -> Date

    /// False until `start()`: the shared service records nothing under unit tests.
    private(set) var isActive: Bool
    private var lastChangeCount: Int
    private var suspendCount = 0
    private var lastPrune = Date.distantPast
    private var timer: Timer?
    /// Set by `start()`; a service built active for a test is ticked by hand.
    private var usesTimer = false

    init(
        store: ClipboardHistoryStore? = nil,
        pasteboard: ClipboardPasteboard? = nil,
        settings: SettingsStorage = .shared,
        frontmostApp: @escaping () -> ClipboardSourceApp = ClipboardHistoryService.frontmostApplication,
        now: @escaping () -> Date = Date.init,
        isActive: Bool = false
    ) {
        self.store = store ?? Self.makeDefaultStore()
        let pasteboard = pasteboard ?? GeneralClipboardPasteboard()
        self.pasteboard = pasteboard
        self.settings = settings
        self.frontmostApp = frontmostApp
        self.now = now
        self.isActive = isActive
        lastChangeCount = pasteboard.changeCount
    }

    nonisolated static func frontmostApplication() -> ClipboardSourceApp {
        let app = NSWorkspace.shared.frontmostApplication
        return ClipboardSourceApp(name: app?.localizedName, bundleID: app?.bundleIdentifier)
    }

    private static func makeDefaultStore() -> ClipboardHistoryStore {
        #if TEST_BUILD
            if let fixture = UITestHarness.clipboardFixture { return ClipboardUITestSample.makeStore(empty: fixture == "empty") }
        #endif
        return ClipboardHistoryStore(directory: ClipboardHistoryStore.defaultDirectory)
    }

    // MARK: - Watching

    /// Prunes, then polls the pasteboard, unless "Keep the clipboard for" is "Never".
    func start() {
        isActive = true
        usesTimer = true
        prune()
        retentionChanged()
    }

    /// Follows "Keep the clipboard for": "Never" stops the polling, any other value starts it. What is
    /// on the pasteboard at the start is not recorded.
    func retentionChanged() {
        guard isActive else { return }
        guard settings.clipboardRetention != .never else {
            timer?.invalidate()
            timer = nil
            return
        }
        prune()
        lastChangeCount = pasteboard.changeCount
        guard usesTimer, timer == nil else { return }
        #if TEST_BUILD
            // The sample history is fixed: no polling over it.
            if UITestHarness.clipboardFixture != nil { return }
        #endif
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        usesTimer = false
        isActive = false
    }

    /// One tick: records a new copy unless Diduny is writing the pasteboard itself.
    func poll() {
        let changeCount = pasteboard.changeCount
        guard settings.clipboardRetention != .never else {
            lastChangeCount = changeCount
            return
        }
        guard changeCount != lastChangeCount else {
            if now().timeIntervalSince(lastPrune) >= Self.pruneInterval { prune() }
            return
        }
        lastChangeCount = changeCount
        guard isActive, suspendCount == 0 else { return }
        capture()
    }

    private func capture() {
        let types = pasteboard.types
        guard Self.skippedTypes.isDisjoint(with: types) else { return }
        let app = frontmostApp()
        if settings.clipboardSkipPasswordManagers, let bundleID = app.bundleID,
           Self.passwordManagerBundleIDs.contains(bundleID)
        {
            return
        }
        var added: ClipboardEntry?
        if types.contains(Self.fileURLType) {
            let urls = pasteboard.fileURLs()
            added = urls.isEmpty ? nil : store.addFiles(urls, app: app, date: now())
        } else if let text = pasteboard.string(), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            added = store.addCopiedText(text, app: app, date: now())
        } else if settings.clipboardKeepScreenshots, let data = pasteboard.imageData() {
            added = store.addImage(data, app: app, date: now())
        }
        if added != nil { prune() }
    }

    func prune() {
        lastPrune = now()
        store.prune(retention: settings.clipboardRetention, now: lastPrune)
    }

    // MARK: - Diduny's own writes

    /// Diduny is about to write the pasteboard itself; nothing is recorded until the matching `resume()`.
    func suspend() {
        suspendCount += 1
    }

    /// Takes the pasteboard as it is now for seen, so the write made under suspension is never recorded.
    func resume() {
        suspendCount = max(0, suspendCount - 1)
        lastChangeCount = pasteboard.changeCount
    }

    /// Runs a pasteboard write of Diduny's own, which the watcher must not record as a copy.
    func withoutCapture<T>(_ write: () throws -> T) rethrows -> T {
        suspend()
        defer { resume() }
        return try write()
    }

    /// One entry for text Diduny delivered ("Dictated into <app>"). `pasted` false: the text was only
    /// copied, so no app is named.
    func recordDelivery(_ text: String, origin: ClipboardEntry.Origin, pasted: Bool) {
        guard isActive, settings.clipboardRetention != .never, settings.clipboardKeepDidunyPastes, !text.isEmpty else { return }
        store.addDidunyText(text, origin: origin, app: pasted ? frontmostApp() : .unknown, date: now())
        prune()
    }

    // MARK: - Page actions

    /// Puts an entry back on the pasteboard: the full text, the full image or the file URLs that still
    /// exist. Adds no entry.
    @discardableResult
    func copyToPasteboard(_ entry: ClipboardEntry) -> Bool {
        withoutCapture {
            if entry.kind == .files {
                let urls = (entry.filePaths ?? []).filter(FileManager.default.fileExists(atPath:)).map(URL.init(fileURLWithPath:))
                guard !urls.isEmpty else { return false }
                pasteboard.write(fileURLs: urls)
            } else if entry.kind == .image {
                guard let data = store.imageData(for: entry) else { return false }
                pasteboard.write(png: data)
            } else {
                guard let text = entry.text else { return false }
                pasteboard.write(text: text)
            }
            return true
        }
    }
}
